"""Render ``summary.json`` of a KV run into ``docs/metrics/kv_paths_<tag>.md`` (+ a copy of the JSON).

``python -m agentic_rag.kvpaths.report <summary.json> [--docs docs/metrics]``  (no GPU needed)
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

HOPS = ["cross_year", "metric_change", "supply_chain", "deep_chain", "aggregate", "join_lookup", "join"]


def _f(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def render(summary: dict) -> str:
    meta = summary.get("_meta", {})
    tag = meta.get("model", "?")
    out = [f"# KV-level access paths — `{tag}`", "",
           "Generated by `python -m agentic_rag.kvpaths.run` then `kvpaths.report`. Greedy decoding, one H20. "
           "`budget` = fraction of *corpus* KV kept per layer and KV head (the system instruction and "
           "end-of-turn tokens are always kept and not counted). `gap` = accuracy(lookup) − accuracy(join) "
           "over paired questions with the same evidence and gold, with a 95% bootstrap interval that "
           "resamples whole supply links. `DiD` = that gap minus the same pairs' gap under the full KV "
           "(the join cost added by compression). Accuracy is lenient (a final `答案：X` counts when the "
           "JSON line is missing); `fmt` = answers right under lenient but wrong under strict JSON parsing, "
           "`strict gap` = the gap under strict parsing. `oracle` keeps only the gold documents and reads "
           "the question over them; `oracle_aware` keeps the same documents but, like `query`/`join`, "
           "keeps the question KV computed over the full context. "
           "Wrong answers: `null` = said the evidence is missing, `near` = a number within 10% of gold "
           "(right document, corrupted digits or adjacent field), `far` = anything else.", ""]
    for size, s in summary.items():
        if size.startswith("_"):
            continue
        m = s.get("meta", {})
        out += [f"## {size} distractors — {m.get('ctx_tokens', '?')} context tokens, {m.get('docs', '?')} docs", "",
                f"Prefill {m.get('prefill_s', '?')} s, full KV {m.get('kv_gb_full', '?')} GB, "
                f"peak GPU memory {m.get('peak_mem_gb', '?')} GB, question scoring {s.get('score_s_mean')} s/q, "
                f"{s.get('n_questions')} questions.", "",
                "| policy | budget | orig acc | " + " | ".join(HOPS) + " | gap (lookup−join) [95% CI] | DiD vs full [95% CI] | strict gap | fmt | wrong: null/near/far | gen s/q |",
                "|---|---|---|" + "---|" * len(HOPS) + "---|---|---|---|---|---|"]
        for c in s["cells"].values():
            g = c.get("paired_gap_lookup_minus_join")
            gs = (f"{g['gap']:+.3f} [{g['lo']:+.2f}, {g['hi']:+.2f}] n={g['n_pairs']}/{g.get('n_links', '?')}"
                  if g else "–")
            dd = c.get("did_vs_full")
            ds = f"{dd['gap']:+.3f} [{dd['lo']:+.2f}, {dd['hi']:+.2f}]" if dd else "–"
            st = c.get("paired_gap_strict")
            ss = f"{st['gap']:+.3f}" if st else "–"
            hops = " | ".join(_f(c["per_hop"].get(h), 2) for h in HOPS)
            b = "–" if c["budget"] is None else (f"{c['budget']:.2f}" if c["policy"] != "oracle" else "–")
            if c["policy"] in ("oracle", "oracle_aware"):
                b = f"({c['kept_frac']:.3f})"
            e = c.get("errors") or {}
            es = f"{e.get('null', 0)}/{e.get('near', 0)}/{e.get('far', 0)}"
            out.append(f"| {c['policy']} | {b} | {_f(c['accuracy_original63'])} | {hops} | {gs} | {ds} | {ss} | {c.get('format_fail', '–')} | {es} | {c['gen_s_mean']} |")
        r = s.get("second_hop_rank") or {}
        if r:
            out += ["", "Rank of the second-hop document (the supplier's report) by per-document attention mass of "
                        "the question tokens, per layer (median over questions; lower is better), vs BM25 on the "
                        "question text:", ""]
            for kind, v in r.items():
                med = v["median_rank_by_layer"]
                out.append(f"- `{kind}`: BM25 median rank {v['bm25_median_rank']} (top-3 {v['bm25_top3_rate']}); "
                           f"attention median rank by layer {med}; best layer {min(range(len(med)), key=med.__getitem__)} "
                           f"(rank {min(med)}); top-3 rate max {max(v['top3_rate_by_layer'])}")
        out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("summary")
    ap.add_argument("--docs", default="docs/metrics")
    a = ap.parse_args(argv)
    s = json.loads(Path(a.summary).read_text())
    tag = s.get("_meta", {}).get("model", Path(a.summary).parent.name)
    d = Path(a.docs)
    d.mkdir(parents=True, exist_ok=True)
    (d / f"kv_paths_{tag}.md").write_text(render(s))
    shutil.copy(a.summary, d / f"kv_paths_summary_{tag}.json")
    print("wrote", d / f"kv_paths_{tag}.md")


if __name__ == "__main__":
    main()
